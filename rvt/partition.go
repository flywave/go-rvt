// Partition stream layout (PartitionStreamVersion 9; 2022/2023 samples +
// REA of TB_Loader.tx — findings R23–R27):
//
//	stream := 12B fixed header
//	          32B page record for page 0     (the classic "44B header")
//	          { 32B page record | page (gzip member) }*
//	          signature blocks
//	          32B terminator record + 64B hash + signature string + padding
//
// Page record (32B, LE): u16 markA, u32 prevLen, u16 markB, u32 kind,
// u32 counter, u32 ownLen, u32 payload, u32 class, u32 flag. It sits
// immediately before its page's gzip member. ownLen = member length + 8
// (the extra 8 bytes correspond to the CRC record OdBmFileCRC::
// verifyAndCutCRC cuts from the raw page read — PageReader::read).
// prevLen = previous member length + 8. class (101/102/103…) tags the
// logical sub-stream the page feeds; both samples interleave three
// sub-streams. kind is 4 for regular pages, 5/6/7 for small or
// 128K-aligned pages [?]. markA/markB are per-file 16-bit markers
// (2023: 0x0e47/0x0e4e; 2022: 0x0de2/0x0de9) [?].
//
// A record with kind==0 && ownLen==0 is a signature record: it is followed
// by ~156B (64B hash + length-prefixed UTF-16 "Data generated by
// Autodesk® Revit®" + trailer) and then the 32B page record of the next
// page (whose first 6 bytes are opaque but markB/kind/ownLen/class parse
// normally). The stream ends with a terminator record (kind==0, ownLen==0,
// prevLen=last page length), the 64B hash, the signature string, the
// header@8 value and zero padding.
//
// Pages whose record and gzip footer both verify are "verified"; their
// decompressed payloads concatenate, per class, into the sub-stream data.
// Pages whose index length is stale by a multiple of 353 bytes (R29/R40:
// incrementally rewritten payloads with unrefreshed index/footer) inflate
// cleanly and are recovered into the sub-stream data, flagged StaleIndex.
// Remaining damaged pages are reported as errors and excluded.

const (
	partitionFixedHeader = 12 // u32 version, u32 [?], u32 [?] (869/817 on samples)
	partitionRecordSize  = 32
	partitionSigGap      = 220 // signature block: 32B record + 156B payload + 32B next record
	depositRecordSize    = 103
	depositField91At     = 4  // u32 91 (0x5b) — version class index? [?]
	depositField91BAt    = 99 // second 91 inside the B block
)

var gzipMagic = []byte{0x1f, 0x8b, 0x08}

// staleIndexDelta is the per-rewrite length deficit of stale-index pages
// (findings R29/R40: -353 per rewrite, -706 = two rewrites).
const staleIndexDelta = 353

// PageRecord is the 32-byte index record preceding one page.
type PageRecord struct {
	MarkA   uint16
	PrevLen uint32 // previous member length + 8
	MarkB   uint16
	Kind    uint32 // 4 regular; 5/6/7 small/128K-aligned [?]; 0 = signature/terminator
	Counter uint32 // declines across the stream [?]
	OwnLen  uint32 // own member length + 8; 0 for signature/terminator records
	Payload uint32 // ~90% of the decompressed size [?]
	Class   uint32 // sub-stream tag (101/102/103…)
	Flag    uint32 // 0 for page records
	IsFirst bool   // record of page 0 (lives inside the stream header, markA=0)
	Opaque  bool   // record after a signature block (markA/prevLen opaque)
}

func parsePageRecord(b []byte) PageRecord {
	return PageRecord{
		MarkA:   binary.LittleEndian.Uint16(b[0:]),
		PrevLen: binary.LittleEndian.Uint32(b[2:]),
		MarkB:   binary.LittleEndian.Uint16(b[6:]),
		Kind:    binary.LittleEndian.Uint32(b[8:]),
		Counter: binary.LittleEndian.Uint32(b[12:]),
		OwnLen:  binary.LittleEndian.Uint32(b[16:]),
		Payload: binary.LittleEndian.Uint32(b[20:]),
		Class:   binary.LittleEndian.Uint32(b[24:]),
		Flag:    binary.LittleEndian.Uint32(b[28:]),
	}
}

func (r PageRecord) isSignature() bool {
	return r.Kind == 0 && r.OwnLen == 0
}

// Page is one gzip member of the page chain.
type Page struct {
	Offset     int // member start offset within the raw stream
	CompLen    int
	DecompLen  int
	Class      uint32
	Kind       uint32
	Record     *PageRecord // record preceding the member, when structurally valid
	RecordOK   bool        // record.ownLen == CompLen+8
	FooterOK   bool        // gzip footer matches the inflated payload
	Readable   bool        // inflate succeeded
	Verified   bool        // RecordOK && FooterOK — payload is trustworthy
	StaleIndex bool        // R40 recovery: index stale by a 353-multiple, payload trusted

	data []byte // decompressed payload (verified + stale-index pages)
}

// PageError reports one damaged region of the stream.
type PageError struct {
	Offset int    `json:"offset"`
	Kind   string `json:"kind"` // inflate | corrupt_data | gap | spurious_magic
	Detail string `json:"detail,omitempty"`
}

// DepositRecord is one 103B counter-stamped record at the head of the
// class-101 sub-stream (A-block + B-block; both halves repeat the counter).
// 2023 counters step +1 (1098306–1098316); 2022 counters jump (99585,
// 394412, …) — semantics [?]. Field91 is 91 (0x5b) on both versions;
// Field1398 is 1398 (2023) / 1340 (2022) — likely per-version class
// indexes (findings R24).
type DepositRecord struct {
	Counter   uint32 `json:"counter"`
	Field91   uint32 `json:"field91"`
	Field1398 uint32 `json:"field1398"`
}

// SubStream is one logical stream reconstructed from the pages of one class.
type SubStream struct {
	Class        uint32
	Pages        int // all real pages of this class (incl. unreadable)
	DataPages    int // pages contributing data (verified + stale-index)
	StalePages   int // recovered stale-index pages (R40)
	LogicalBytes int
	Deposits     []DepositRecord
	Data         []byte // concatenation of verified + stale-index payloads

	// Records/Walk are populated for the deposit-bearing sub-stream (the
	// [counter][size][body][echo] object-record framing — R42/R44); other
	// sub-streams carry different framing and are not walked.
	Records   []ObjectRecord
	WalkStats WalkStats
}

// SubStreamInfo is the JSON summary of one sub-stream.
type SubStreamInfo struct {
	Class        uint32       `json:"class"`
	Pages        int          `json:"pages"`
	DataPages    int          `json:"data_pages"`
	StalePages   int          `json:"stale_pages,omitempty"`
	LogicalBytes int          `json:"logical_bytes"`
	Deposits     int          `json:"deposits,omitempty"`
	FirstCounter uint32       `json:"first_counter,omitempty"`
	LastCounter  uint32       `json:"last_counter,omitempty"`
	Records      int          `json:"records,omitempty"`
	WalkBytes    int          `json:"walk_bytes,omitempty"`
	WalkResyncs  int          `json:"walk_resyncs,omitempty"`
	Classes      []ClassCount `json:"classes,omitempty"`
}

// PartitionInfo is the JSON summary of one Partitions/<n> stream.
type PartitionInfo struct {
	Name             string          `json:"name"`
	Version          uint32          `json:"version"`
	MarkA            uint16          `json:"mark_a,omitempty"`
	MarkB            uint16          `json:"mark_b,omitempty"`
	HeaderField8     uint32          `json:"header_field8"` // 869/817 — echoed inside signature records [?]
	Pages            int             `json:"pages"`         // real pages (readable + unreadable)
	ReadablePages    int             `json:"readable_pages"`
	VerifiedPages    int             `json:"verified_pages"`
	StaleIndexPages  int             `json:"stale_index_pages"`  // R40 recovered
	CorruptDataPages int             `json:"corrupt_data_pages"` // inflated but footer/index mismatch
	UnreadablePages  int             `json:"unreadable_pages"`   // inflate failed
	SpuriousMagics   int             `json:"spurious_magics,omitempty"`
	SignatureRecords int             `json:"signature_records"`
	SignatureText    string          `json:"signature_text,omitempty"`
	Terminator       bool            `json:"terminator"`
	LogicalBytes     int             `json:"logical_bytes"` // verified pages only
	SubStreams       []SubStreamInfo `json:"sub_streams,omitempty"`
	DepositCount     int             `json:"deposit_count"` // deposits of the first sub-stream that has any
	FirstCounter     uint32          `json:"first_counter,omitempty"`
	LastCounter      uint32          `json:"last_counter,omitempty"`
	PageErrors       []PageError     `json:"page_errors,omitempty"`
	HeaderHex        string          `json:"header_hex"` // 12B fixed header
}

// Partition is the fully parsed partition container.
type Partition struct {
	Info           PartitionInfo
	Pages          []Page
	SubStreams     []*SubStream
	SignatureText  string
	SignatureCount int
	Errors         []PageError
}

// ReadPartition parses one Partitions/<n> stream body. Corrupt regions are
// reported in Errors / Info.PageErrors; the sub-stream data only contains
// verified and stale-index-recovered pages.
func ReadPartition(name string, stream []byte) (*Partition, error) {
	return ReadPartitionWithLookup(name, stream, nil)
}

// ReadPartitionWithLookup is ReadPartition with a class-index lookup
// (rvt/classindex) used to resolve record class names during the
// sub-stream record walk.
func ReadPartitionWithLookup(name string, stream []byte, lookup func(int16) string) (*Partition, error) {
	if len(stream) < partitionFixedHeader+partitionRecordSize {
		return nil, fmt.Errorf("rvt: partition %s: short stream (%d bytes)", name, len(stream))
	}
	p := &Partition{}
	info := &p.Info
	info.Name = name
	info.Version = binary.LittleEndian.Uint32(stream[0:])
	info.HeaderField8 = binary.LittleEndian.Uint32(stream[8:])
	info.HeaderHex = fmt.Sprintf("%x", stream[:partitionFixedHeader])

	rec0 := parsePageRecord(stream[partitionFixedHeader:])
	rec0.IsFirst = true
	markB := rec0.MarkB

	pos := partitionFixedHeader + partitionRecordSize
	var markA uint16
	lastComp := -1 // previous real page's compressed length, for the terminator check

	for pos < len(stream) {
		if !bytes.HasPrefix(stream[pos:], gzipMagic) {
			next := bytes.Index(stream[pos:], gzipMagic)
			if next < 0 {
				p.classifyTail(stream[pos:], markB, lastComp, pos)
				break
			}
			p.classifyGap(stream[pos:pos+next], markB, pos)
			pos += next
			continue
		}
		m, err := zg.DecompressOne(stream, pos)
		if err != nil {
			// Either a real page whose deflate data is damaged, or a magic
			// hit inside foreign bytes. The preceding record decides.
			if rec, ok := recordBefore(stream, pos, markB); ok && plausibleRecord(rec) {
				pg := Page{Offset: pos, Class: rec.Class, Kind: rec.Kind, Record: &rec}
				p.appendPage(pg)
				p.errAt(pos, "inflate", err.Error())
			} else {
				info.SpuriousMagics++
			}
			n := bytes.Index(stream[pos+3:], gzipMagic)
			if n < 0 {
				p.classifyTail(stream[pos+3:], markB, lastComp, pos)
				break
			}
			pos += 3 + n
			continue
		}
		pg := Page{
			Offset:    pos,
			CompLen:   m.End - pos,
			DecompLen: len(m.Data),
			FooterOK:  m.FooterCRCOK && m.FooterSizeOK,
			Readable:  true,
		}
		if rec, ok := recordBefore(stream, pos, markB); ok {
			pg.Class = rec.Class
			pg.Kind = rec.Kind
			pg.Record = &rec
			pg.RecordOK = rec.OwnLen == uint32(pg.CompLen)+8
			if rec.MarkA != 0 && markA == 0 {
				markA = rec.MarkA
			}
		}
		if pg.RecordOK && pg.FooterOK {
			pg.Verified = true
			pg.data = m.Data
		} else if pg.Record != nil {
			// R40: pages rewritten in place with a stale index/footer show a
			// constant length deficit that is a multiple of 353 bytes; the
			// payload inflates cleanly (probe: record structure intact), so
			// it is recovered rather than discarded.
			if d := int(pg.Record.OwnLen) - (pg.CompLen + 8); d < 0 && d%staleIndexDelta == 0 {
				pg.StaleIndex = true
				pg.data = m.Data
			}
		}
		p.appendPage(pg)
		if !pg.Verified && !pg.StaleIndex {
			detail := "gzip footer mismatch"
			if pg.Record != nil && !pg.RecordOK {
				detail = fmt.Sprintf("index len %d, actual %d", pg.Record.OwnLen, pg.CompLen+8)
			}
			p.errAt(pos, "corrupt_data", detail)
		}
		lastComp = pg.CompLen
		pos = m.End
	}

	info.MarkA = markA
	info.MarkB = markB
	p.assembleSubStreams(lookup)
	p.fillSummary()
	return p, nil
}

// recordBefore returns the 32B record immediately preceding offset, when
// its markB slot matches the stream's marker.
func recordBefore(stream []byte, pos int, markB uint16) (PageRecord, bool) {
	if pos < partitionRecordSize {
		return PageRecord{}, false
	}
	rec := parsePageRecord(stream[pos-partitionRecordSize : pos])
	if rec.MarkB != markB || markB == 0 {
		return PageRecord{}, false
	}
	return rec, true
}

// plausibleRecord gates whether a magic that fails to inflate is a real
// (damaged) page: a plausible index record with a sane own length.
func plausibleRecord(rec PageRecord) bool {
	return !rec.isSignature() && rec.OwnLen >= 8 && rec.OwnLen < 0x10000
}

// classifyGap inspects the bytes between two members: a bare 32B link
// record, a 220B signature block, or damaged bytes.
func (p *Partition) classifyGap(gap []byte, markB uint16, offset int) {
	if len(gap) == partitionRecordSize {
		return // plain link record
	}
	if len(gap) >= partitionSigGap {
		rec := parsePageRecord(gap)
		if rec.MarkB == markB && rec.isSignature() {
			next := parsePageRecord(gap[len(gap)-partitionRecordSize:])
			if next.MarkB == markB {
				p.SignatureCount++
				if p.SignatureText == "" {
					p.SignatureText = extractSignatureText(gap[partitionRecordSize:])
				}
				if len(gap) > partitionSigGap {
					// a page after the signature block lost its gzip magic
					p.errAt(offset+partitionSigGap, "gap",
						fmt.Sprintf("%d damaged bytes after signature block", len(gap)-partitionSigGap))
				}
				return
			}
		}
	}
	p.errAt(offset, "gap", fmt.Sprintf("%d bytes between pages", len(gap)))
}

// classifyTail inspects the bytes after the last member: the expected
// terminator record + hash + signature string, or trailing damage.
func (p *Partition) classifyTail(rest []byte, markB uint16, lastComp int, offset int) {
	if len(rest) < partitionRecordSize {
		if len(rest) > 0 {
			p.errAt(offset, "gap", fmt.Sprintf("%d trailing bytes", len(rest)))
		}
		return
	}
	rec := parsePageRecord(rest)
	if rec.MarkB == markB && rec.isSignature() &&
		(lastComp < 0 || rec.PrevLen == uint32(lastComp)+8) {
		p.Info.Terminator = true
		if p.SignatureText == "" {
			p.SignatureText = extractSignatureText(rest[partitionRecordSize:])
		}
		return
	}
	p.errAt(offset, "gap", fmt.Sprintf("%d trailing bytes, no terminator record", len(rest)))
}

var signatureHead = []byte{0x44, 0x00, 0x61, 0x00, 0x74, 0x00, 0x61, 0x00} // UTF-16LE "Data"

// extractSignatureText pulls the length-prefixed UTF-16 signature string
// ("Data generated by Autodesk® Revit®") out of a signature payload.
func extractSignatureText(b []byte) string {
	i := bytes.Index(b, signatureHead)
	if i < 4 {
		return ""
	}
	n := int(binary.LittleEndian.Uint32(b[i-4:]))
	if n <= 0 || n > 128 || i+n*2 > len(b) {
		return ""
	}
	units := make([]uint16, n)
	for k := range units {
		units[k] = binary.LittleEndian.Uint16(b[i+k*2:])
	}
	return string(utf16.Decode(units))
}

func (p *Partition) appendPage(pg Page) {
	p.Pages = append(p.Pages, pg)
}

func (p *Partition) errAt(offset int, kind, detail string) {
	p.Errors = append(p.Errors, PageError{Offset: offset, Kind: kind, Detail: detail})
}

// assembleSubStreams groups real pages by class and concatenates the
// verified payloads.
func (p *Partition) assembleSubStreams(lookup func(int16) string) {
	byClass := map[uint32]*SubStream{}
	for i := range p.Pages {
		pg := &p.Pages[i]
		if pg.Record == nil {
			continue // no class tag; counted in Info only
		}
		ss := byClass[pg.Class]
		if ss == nil {
			ss = &SubStream{Class: pg.Class}
			byClass[pg.Class] = ss
		}
		ss.Pages++
		if pg.Verified || pg.StaleIndex {
			ss.DataPages++
			if pg.StaleIndex {
				ss.StalePages++
			}
			ss.Data = append(ss.Data, pg.data...)
		}
	}
	for _, ss := range byClass {
		ss.LogicalBytes = len(ss.Data)
		ss.Deposits = scanDeposits(ss.Data)
		// Object-record walk: only the deposit-bearing sub-stream carries
		// the validated [counter][size][body][echo] framing.
		if len(ss.Deposits) > 0 {
			ss.Records, ss.WalkStats = walkRecords(ss.Data, len(ss.Deposits)*depositRecordSize, lookup)
		}
		p.SubStreams = append(p.SubStreams, ss)
	}
	sort.Slice(p.SubStreams, func(i, j int) bool {
		return p.SubStreams[i].Class < p.SubStreams[j].Class
	})
}

// scanDeposits detects the leading deposit records of a sub-stream:
// 103B records shaped [u32 counter][u32 91][u32 idx]…[counter repeat]
// …[u32 91 @99]. The counter steps +1 on 2023 but not on 2022, so no
// sequencing is required — only the fixed shape.
func scanDeposits(b []byte) []DepositRecord {
	var out []DepositRecord
	for pos := 0; pos+depositRecordSize <= len(b); pos += depositRecordSize {
		c := binary.LittleEndian.Uint32(b[pos:])
		if binary.LittleEndian.Uint32(b[pos+depositField91At:]) != 91 {
			break
		}
		if binary.LittleEndian.Uint32(b[pos+depositField91BAt:]) != 91 {
			break
		}
		repeat := false
		for q := pos + 58; q+4 <= pos+72 && q+4 <= len(b); q++ {
			if binary.LittleEndian.Uint32(b[q:]) == c {
				repeat = true
				break
			}
		}
		if !repeat {
			break
		}
		out = append(out, DepositRecord{
			Counter:   c,
			Field91:   91,
			Field1398: binary.LittleEndian.Uint32(b[pos+8:]),
		})
	}
	return out
}

func (p *Partition) fillSummary() {
	info := &p.Info
	info.Pages = len(p.Pages)
	for i := range p.Pages {
		pg := &p.Pages[i]
		if pg.Readable {
			info.ReadablePages++
		} else {
			info.UnreadablePages++
		}
		if pg.Verified {
			info.VerifiedPages++
		} else if pg.StaleIndex {
			info.StaleIndexPages++
		} else if pg.Readable {
			info.CorruptDataPages++
		}
	}
	for _, ss := range p.SubStreams {
		ssi := SubStreamInfo{
			Class:        ss.Class,
			Pages:        ss.Pages,
			DataPages:    ss.DataPages,
			StalePages:   ss.StalePages,
			LogicalBytes: ss.LogicalBytes,
			Deposits:     len(ss.Deposits),
			Records:      ss.WalkStats.Records,
			WalkBytes:    ss.WalkStats.BytesWalked,
			WalkResyncs:  ss.WalkStats.Resyncs,
		}
		if len(ss.Records) > 0 {
			ssi.Classes = CensusClasses(ss.Records)
		}
		if len(ss.Deposits) > 0 {
			ssi.FirstCounter = ss.Deposits[0].Counter
			ssi.LastCounter = ss.Deposits[len(ss.Deposits)-1].Counter
			if info.DepositCount == 0 {
				info.DepositCount = len(ss.Deposits)
				info.FirstCounter = ssi.FirstCounter
				info.LastCounter = ssi.LastCounter
			}
		}
		info.LogicalBytes += ss.LogicalBytes
		info.SubStreams = append(info.SubStreams, ssi)
	}
	info.SignatureRecords = p.SignatureCount
	info.SignatureText = p.SignatureText
	if len(p.Errors) > 0 {
		info.PageErrors = p.Errors
	}
}
