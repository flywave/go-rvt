// ---- synthetic fixture -------------------------------------------------

func le32(v uint32) []byte { b := make([]byte, 4); binary.LittleEndian.PutUint32(b, v); return b }
func le16(v uint16) []byte { b := make([]byte, 2); binary.LittleEndian.PutUint16(b, v); return b }

func gzmem(t *testing.T, data []byte) []byte {
	t.Helper()
	var buf bytes.Buffer
	w := gzip.NewWriter(&buf)
	if _, err := w.Write(data); err != nil {
		t.Fatal(err)
	}
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func recBytes(markA uint16, prevLen uint32, markB uint16, kind, counter, ownLen, payload, class, flag uint32) []byte {
	b := make([]byte, 32)
	copy(b[0:], le16(markA))
	copy(b[2:], le32(prevLen))
	copy(b[6:], le16(markB))
	copy(b[8:], le32(kind))
	copy(b[12:], le32(counter))
	copy(b[16:], le32(ownLen))
	copy(b[20:], le32(payload))
	copy(b[24:], le32(class))
	copy(b[28:], le32(flag))
	return b
}

func utf16le(s string) []byte {
	units := []rune(s)
	out := make([]byte, len(units)*2)
	for i, u := range units {
		binary.LittleEndian.PutUint16(out[i*2:], uint16(u))
	}
	return out
}

// depositRec builds one 103B deposit record (2023 shape: counter repeat at
// 66, 91 at 4 and 99).
func depositRec(counter uint32) []byte {
	b := make([]byte, 103)
	copy(b[0:], le32(counter))
	copy(b[4:], le32(91))
	copy(b[8:], le32(1398))
	for i := 14; i < 46; i++ {
		b[i] = 0xff
	}
	copy(b[66:], le32(counter))
	copy(b[99:], le32(91))
	return b
}

const sigText = "Data generated by Autodesk® Revit®"

// buildSyntheticPartition assembles a well-formed v9 partition stream with
// three pages (classes 101/102/103), one signature block and a terminator.
func buildSyntheticPartition(t *testing.T) []byte {
	t.Helper()
	var s bytes.Buffer
	s.Write(le32(9))   // version
	s.Write(le32(0))   // [?]
	s.Write(le32(869)) // header field 8

	// page 0 (class 101): two deposit records + filler
	var p0 bytes.Buffer
	p0.Write(depositRec(1000))
	p0.Write(depositRec(1001))
	p0.Write(objRec(5000, 1398, bytes.Repeat([]byte{0x77}, 40)))
	p0.Write(bytes.Repeat([]byte{0x55}, 300))
	m0 := gzmem(t, p0.Bytes())
	s.Write(recBytes(0, 0, 0x0e4e, 4, 1, uint32(len(m0)+8), 0, 101, 0))
	s.Write(m0)

	// page 1 (class 102)
	m1 := gzmem(t, bytes.Repeat([]byte{0xAB}, 5000))
	s.Write(recBytes(0x0e47, uint32(len(m0)+8), 0x0e4e, 4, 2, uint32(len(m1)+8), 0, 102, 0))
	s.Write(m1)

	// signature block: 32B sig record + 156B payload + 32B next record
	sigStr := utf16le(sigText)
	sigPayload := make([]byte, 156)
	for i := 0; i < 64; i++ {
		sigPayload[i] = byte(i * 7)
	}
	copy(sigPayload[64:], le32(uint32(len(sigStr)/2)))
	copy(sigPayload[68:], sigStr)
	copy(sigPayload[150:], le32(868)) // tail value observed next to header field 8
	s.Write(recBytes(0x0e47, uint32(len(m1)+8), 0x0e4e, 0, 0, 0, 0, 0x400e61, 0x7c700000))
	s.Write(sigPayload)

	// page 2 (class 103) — record after a signature block carries opaque
	// markA/prevLen but a valid markB/kind/ownLen/class.
	m2 := gzmem(t, bytes.Repeat([]byte{0xCD}, 3000))
	s.Write(recBytes(0x9665, 0x432bf4d6, 0x0e4e, 4, 3, uint32(len(m2)+8), 0, 103, 0))
	s.Write(m2)

	// terminator record + hash + signature string + tail + padding
	s.Write(recBytes(0x0e47, uint32(len(m2)+8), 0x0e4e, 0, 0, 0, 0, 0x400e61, 0x99c90000))
	hash := make([]byte, 64)
	for i := range hash {
		hash[i] = byte(i * 13)
	}
	s.Write(hash)
	s.Write(le32(uint32(len(sigStr) / 2)))
	s.Write(sigStr)
	s.Write(le16(869))
	s.Write(le32(0))
	s.Write(le32(0xFFFFFFFF))
	s.Write(bytes.Repeat([]byte{0}, 64))
	return s.Bytes()
}

func TestPartitionSynthetic(t *testing.T) {
	stream := buildSyntheticPartition(t)
	p, err := ReadPartition("7", stream)
	if err != nil {
		t.Fatal(err)
	}
	info := p.Info
	if info.Version != 9 {
		t.Errorf("version %d", info.Version)
	}
	if info.MarkA != 0x0e47 || info.MarkB != 0x0e4e {
		t.Errorf("markers %04x/%04x", info.MarkA, info.MarkB)
	}
	if info.HeaderField8 != 869 {
		t.Errorf("header field8 %d", info.HeaderField8)
	}
	if info.Pages != 3 || info.VerifiedPages != 3 || info.ReadablePages != 3 {
		t.Errorf("pages total=%d readable=%d verified=%d", info.Pages, info.ReadablePages, info.VerifiedPages)
	}
	if info.CorruptDataPages != 0 || info.UnreadablePages != 0 || info.SpuriousMagics != 0 {
		t.Errorf("corrupt=%d unreadable=%d spurious=%d", info.CorruptDataPages, info.UnreadablePages, info.SpuriousMagics)
	}
	if len(info.SubStreams) != 3 {
		t.Fatalf("sub-streams %v", info.SubStreams)
	}
	wantClass := []uint32{101, 102, 103}
	for i, ss := range info.SubStreams {
		if ss.Class != wantClass[i] || ss.Pages != 1 || ss.DataPages != 1 {
			t.Errorf("sub-stream %d: %+v", i, ss)
		}
	}
	if ss := info.SubStreams[0]; ss.LogicalBytes != 2*103+54+300 {
		t.Errorf("class101 logical %d", ss.LogicalBytes)
	}
	if info.DepositCount != 2 || info.FirstCounter != 1000 || info.LastCounter != 1001 {
		t.Errorf("deposits %d counters %d..%d", info.DepositCount, info.FirstCounter, info.LastCounter)
	}
	if len(p.SubStreams[0].Deposits) != 2 {
		t.Errorf("deposit records %d", len(p.SubStreams[0].Deposits))
	}
	if d := p.SubStreams[0].Deposits[0]; d.Counter != 1000 || d.Field91 != 91 || d.Field1398 != 1398 {
		t.Errorf("deposit 0 %+v", d)
	}
	if info.SignatureRecords != 1 || info.SignatureText != sigText {
		t.Errorf("signature %d %q", info.SignatureRecords, info.SignatureText)
	}
	if !info.Terminator {
		t.Error("terminator not detected")
	}
	if len(info.PageErrors) != 0 {
		t.Errorf("unexpected errors %v", info.PageErrors)
	}
	// sub-stream data check: class 101 data starts with the deposit records
	if !bytes.HasPrefix(p.SubStreams[0].Data, depositRec(1000)) {
		t.Error("class101 data does not start with deposit 1000")
	}
	// object-record walk ran on the deposit-bearing sub-stream
	if len(p.SubStreams[0].Records) != 1 {
		t.Fatalf("records %d (want 1)", len(p.SubStreams[0].Records))
	}
	r := p.SubStreams[0].Records[0]
	if r.Counter != 5000 || r.ClassIndex != 1398 {
		t.Errorf("record %+v", r)
	}
}

func TestPartitionSyntheticCorrupt(t *testing.T) {
	stream := buildSyntheticPartition(t)
	// Flip bytes inside page 1's deflate data: page 1 starts at the second
	// gzip magic in the stream; flip well past its 10B header.
	i0 := bytes.Index(stream, []byte{0x1f, 0x8b, 0x08})
	i1 := i0 + 3 + bytes.Index(stream[i0+3:], []byte{0x1f, 0x8b, 0x08})
	if i0 < 0 || i1 <= i0 {
		t.Fatal("cannot locate member 1")
	}
	flipAt := i1 + 20
	for i := flipAt; i < flipAt+16; i++ {
		stream[i] ^= 0xFF
	}
	p, err := ReadPartition("7", stream)
	if err != nil {
		t.Fatal(err)
	}
	info := p.Info
	if info.VerifiedPages != 2 {
		t.Errorf("verified %d (want 2)", info.VerifiedPages)
	}
	if info.CorruptDataPages+info.UnreadablePages != 1 {
		t.Errorf("corrupt=%d unreadable=%d (want one damaged page)", info.CorruptDataPages, info.UnreadablePages)
	}
	// class 103 page after the damage must still verify
	var ss103 *SubStreamInfo
	for i := range info.SubStreams {
		if info.SubStreams[i].Class == 103 {
			ss103 = &info.SubStreams[i]
		}
	}
	if ss103 == nil || ss103.DataPages != 1 {
		t.Errorf("class103 after corruption: %+v", ss103)
	}
	if len(info.PageErrors) == 0 {
		t.Error("no page errors reported")
	}
}

